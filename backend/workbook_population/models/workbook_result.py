"""Result model returned by the workbook population layer."""

from pydantic import BaseModel, ConfigDict, Field


class WorkbookResult(BaseModel):
    """Final Excel workbook generation result and sheet-level audit metadata."""

    model_config = ConfigDict(
        extra="forbid",
        json_schema_extra={
            "examples": [
                {
                    "output_file_path": "output/company_model.xlsx",
                    "workbook_mode": "template",
                    "workbook_match_score": 92.5,
                    "sheets_reused": ["Income Statement", "Balance Sheet"],
                    "sheets_replaced": ["Cash Flow"],
                    "sheets_created": ["Debt Schedule"],
                    "metrics_written": 432,
                    "warnings": [],
                }
            ]
        },
    )

    output_file_path: str = Field(
        ...,
        min_length=1,
        description="Filesystem path to the generated .xlsx workbook.",
        examples=["output/company_model.xlsx"],
    )
    workbook_mode: str = Field(
        ...,
        min_length=1,
        description="Workbook generation mode: template, user_decision, or dynamic.",
        examples=["template"],
    )
    workbook_match_score: float | None = Field(
        ...,
        ge=0,
        le=100,
        description="Aggregate workbook compatibility score when a template was evaluated.",
        examples=[97.5],
    )
    sheets_reused: list[str] = Field(
        default_factory=list,
        description="Compatible template sheets reused without structural changes.",
        examples=[["Income Statement", "Balance Sheet"]],
    )
    sheets_replaced: list[str] = Field(
        default_factory=list,
        description="Incompatible template sheets removed and regenerated.",
        examples=[["Cash Flow"]],
    )
    sheets_created: list[str] = Field(
        default_factory=list,
        description="Missing or dynamic worksheets generated by this layer.",
        examples=[["Debt Schedule", "Inventory Note"]],
    )
    metrics_written: int = Field(
        ...,
        ge=0,
        description="Number of financial metric values written to workbook cells.",
        examples=[432],
    )
    warnings: list[str] = Field(
        default_factory=list,
        description="Warnings produced during validation or workbook generation.",
    )
